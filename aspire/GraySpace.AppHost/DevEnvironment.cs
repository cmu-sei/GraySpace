using System.Text.RegularExpressions;

/// <summary>Paths in the GraySpace checkout and the generated configuration the AppHost runs with.</summary>
internal sealed partial class DevEnvironment
{
    public DevEnvironment(string appHostDirectory)
    {
        Root = Path.GetFullPath(Path.Combine(appHostDirectory, "..", ".."));
        Data = Path.Combine(Root, "aspire", ".data");
        Cache = Environment.GetEnvironmentVariable("GRAYSPACE_DEV_CACHE")
            ?? Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.UserProfile), ".cache", "grayspace-dev");
        Directory.CreateDirectory(Data);
    }

    /// <summary>The repository root (the directory with Taskfile.yml).</summary>
    public string Root { get; }

    /// <summary>aspire/.data: generated configs and the local services' state. Git-ignored.</summary>
    public string Data { get; }

    /// <summary>Where scripts/install-tool.sh puts Prometheus.</summary>
    public string Cache { get; }

    public string Backend => Path.Combine(Root, "grayspace-web", "backend");
    public string Frontend => Path.Combine(Root, "grayspace-web", "frontend");
    public string BackendPython => Path.Combine(Backend, ".venv", "bin", "python");

    public string Repo(params string[] parts) => Path.Combine([Root, .. parts]);

    /// <summary>A file under aspire/.data, its directory created.</summary>
    public string DataPath(params string[] parts)
    {
        var path = Path.Combine([Data, .. parts]);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        return path;
    }

    /// <summary>A directory under aspire/.data, created.</summary>
    public string DataDir(params string[] parts) => Directory.CreateDirectory(Path.Combine([Data, .. parts])).FullName;

    /// <summary>The topology the simulated deployment shows: the configured tfvars, the deployed one, or the golden fixture.</summary>
    public string SimulatedTfvars(string? configured)
    {
        if (!string.IsNullOrWhiteSpace(configured))
        {
            var path = Path.IsPathRooted(configured) ? configured : Repo(configured);
            return File.Exists(path) ? path : throw new FileNotFoundException($"GraySpace:Tfvars {path} does not exist");
        }
        var parsed = Repo("terraform", "terraform.tfvars.json");
        return File.Exists(parsed) ? parsed : Repo("tests", "golden", "tfvars-full.json");
    }

    /// <summary>The first of the commands that exists: an absolute path, or a name on PATH.</summary>
    public static string? Which(params string[] candidates)
    {
        foreach (var candidate in candidates)
        {
            if (Path.IsPathRooted(candidate))
            {
                if (File.Exists(candidate)) return candidate;
                continue;
            }
            foreach (var dir in (Environment.GetEnvironmentVariable("PATH") ?? "").Split(':', StringSplitOptions.RemoveEmptyEntries))
            {
                var path = Path.Combine(dir, candidate);
                if (File.Exists(path)) return path;
            }
        }
        return null;
    }

    [GeneratedRegex(@"^\s*export\s+([A-Za-z_][A-Za-z0-9_]*)=(.*)$")]
    private static partial Regex ExportLine();

    /// <summary>
    /// The <c>export NAME=value</c> lines of .environment (or environment), the file
    /// scripts/setup-env.sh writes. Values that expand other variables are skipped.
    /// </summary>
    public (string Path, Dictionary<string, string> Values)? ReadEnvironmentFile()
    {
        foreach (var name in new[] { ".environment", "environment" })
        {
            var path = Repo(name);
            if (!File.Exists(path)) continue;
            var values = new Dictionary<string, string>();
            foreach (var line in File.ReadLines(path))
            {
                var match = ExportLine().Match(line);
                if (!match.Success) continue;
                var value = match.Groups[2].Value.Trim();
                if (value.Length >= 2 && (value[0] == '"' || value[0] == '\'') && value[^1] == value[0])
                {
                    value = value[1..^1];
                }
                if (value.Contains('$')) continue;
                values[match.Groups[1].Value] = value;
            }
            return (path, values);
        }
        return null;
    }

    /// <summary>Prometheus scraping the router-metrics simulator, labelled as a deployment's frr and node jobs.</summary>
    public string WritePrometheusConfig(int routerMetricsPort, int prometheusPort)
    {
        var path = DataPath("prometheus", "prometheus.yml");
        File.WriteAllText(path, $"""
            # Generated by the GraySpace AppHost. The simulator labels every series with
            # instance="<router>", which honor_labels keeps, as relabelling does in a deployment.
            global:
              scrape_interval: 5s
              evaluation_interval: 5s
            scrape_configs:
              - job_name: prometheus
                static_configs:
                  - targets: ["localhost:{prometheusPort}"]
              - job_name: frr
                honor_labels: true
                metrics_path: /metrics/frr
                static_configs:
                  - targets: ["localhost:{routerMetricsPort}"]
              - job_name: node
                honor_labels: true
                metrics_path: /metrics/node
                static_configs:
                  - targets: ["localhost:{routerMetricsPort}"]
            """);
        return path;
    }
}
