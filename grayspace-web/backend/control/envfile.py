"""Deployment environment files: shell that sources the site's file, then exports the deployment's
own settings. Terraform, Ansible, task and the worker's job_env() all read them as they read
.environment today (services/slices/environment.py)."""
import os
import shlex
import subprocess
from pathlib import Path
from typing import Dict, Iterable, Optional

HEADER = "# Generated by the GraySpace control plane for deployment {id}; change it through\n" \
         "# PATCH /api/v1/deployments/{id} and Admin > Platform. Edits here are overwritten.\n"


def load(path: Path) -> Dict[str, str]:
    """The variables a shell has after sourcing the file (as services/slices/environment._load_env)."""
    out = subprocess.run(
        ["bash", "-c", 'set -a; source "$1" >/dev/null; env -0', "bash", str(path)],
        capture_output=True, check=True, cwd=str(path.parent),
        env={"PATH": os.environ.get("PATH", "/usr/bin:/bin"), "HOME": os.environ.get("HOME", "/root")},
    ).stdout.decode()
    env = dict(item.split("=", 1) for item in out.split("\0") if "=" in item)
    for name in ("PWD", "OLDPWD", "SHLVL", "_"):
        env.pop(name, None)
    return env


def render(deployment_id: str, site: Optional[Path], exports: Dict[str, str], unsets: Iterable[str] = ()) -> str:
    """unsets: the site's settings the deployment doesn't take (its connections decide them)."""
    lines = [HEADER.format(id=deployment_id)]
    if site is not None:
        lines.append(f"source {shlex.quote(str(site))}\n")
    unsets = list(unsets)
    if unsets:
        lines.append(f"unset {' '.join(unsets)}\n")
    for name, value in exports.items():
        lines.append(f"export {name}={shlex.quote(value)}\n")
    return "".join(lines)


def write(path: Path, text: str):
    tmp = path.with_suffix(".tmp")
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as f:
        f.write(text)
    os.replace(tmp, path)
